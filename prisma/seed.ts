import "dotenv/config";
import { Prisma, PrismaClient } from "@prisma/client";

const prisma = new PrismaClient();

const siteName = process.env.SITE_NAME ?? "Critiqo";
const baseUrl = (process.env.SITE_URL ?? "http://localhost:3000").replace(
  /\/+$/,
  "",
);
const defaultOgImage =
  process.env.SEO_DEFAULT_OG_IMAGE ?? `${baseUrl}/images/default-og.png`;
const defaultDescription =
  process.env.SEO_DEFAULT_DESCRIPTION ??
  "Discover trusted product reviews, compare experiences, and make informed buying decisions.";
const legacyGeneratedDescriptionPattern = new RegExp(
  ["Generated by ", "create next app"].join(""),
  "gi",
);
const cleanDefaultDescription = defaultDescription.replace(
  legacyGeneratedDescriptionPattern,
  "Discover trusted product reviews with Critiqo.",
);
const defaultTitle =
  process.env.SEO_DEFAULT_TITLE ?? "Critiqo | Trusted Product Reviews";

const defaultOrganizationSchema = {
  "@context": "https://schema.org",
  "@type": "Organization",
  name: siteName,
  url: baseUrl,
  logo: defaultOgImage,
};

